import logging
from pathlib import Path

import streamlit as st

from credit_rag.assistant.assistant import CreditAnalystAssistant

PROJECT_DIR = Path(__file__).resolve().parent

FACT_STORE_PATH = (
    PROJECT_DIR
    / "data"
    / "processed"
    / "financial_facts.jsonl"
)

logger = logging.getLogger(__name__)


@st.cache_resource
def load_assistant() -> CreditAnalystAssistant:
    """
    Загружает CreditAnalystAssistant один раз.

    Streamlit повторно выполняет app.py при взаимодействии
    с интерфейсом, поэтому тяжелые RAG-компоненты
    необходимо кэшировать.
    """

    return CreditAnalystAssistant(
        fact_store_path=FACT_STORE_PATH
    )


st.set_page_config(
    page_title="Помощник кредитного аналитика",
    page_icon="📊",
    layout="centered",
)


# -----------------------------------------------------------------------------
# Боковая панель
# -----------------------------------------------------------------------------

with st.sidebar:
    st.header(
        "О системе"
    )

    st.write(
        "Помощник анализирует годовые отчеты "
        "и финансовую отчетность компаний."
    )

    st.subheader(
        "Компании"
    )

    st.markdown(
        """
- ЛУКОЙЛ
- Роснефть
- Татнефть
"""
    )

    st.subheader(
        "Периоды"
    )

    st.markdown(
        """
- 2024
- 2025
"""
    )

    st.subheader(
        "Что можно спросить"
    )

    st.markdown(
        """
**Финансовый факт**

> Какая выручка Роснефти за 2025 год?

**Динамика**

> Как изменилась выручка Роснефти с 2024 по 2025 год?

**Расчетный показатель**

> Какой Net Debt / EBITDA у ЛУКОЙЛа за 2025 год?

**Сравнение компаний**

> Сравни выручку ЛУКОЙЛа и Роснефти за 2025 год.

**Вопрос по годовому отчету**

> Какие климатические риски описывает ЛУКОЙЛ в отчете за 2025 год?
"""
    )

    st.divider()

    st.caption(
        "Широкие качественные вопросы могут покрывать "
        "не все аспекты большого годового отчета."
    )


# -----------------------------------------------------------------------------
# Основная часть
# -----------------------------------------------------------------------------

st.title(
    "📊 Помощник кредитного аналитика"
)

st.write(
    "Задавайте вопросы по годовым отчетам и "
    "финансовой отчетности ЛУКОЙЛа, Роснефти и Татнефти."
)

st.caption(
    "Система автоматически определяет тип вопроса "
    "и выбирает RAG, структурированные финансовые данные "
    "или детерминированный расчет."
)


# -----------------------------------------------------------------------------
# Проверка необходимых данных
# -----------------------------------------------------------------------------

if not FACT_STORE_PATH.exists():
    st.error(
        "Не найдено хранилище финансовых фактов."
    )

    st.code(
        "uv run python scripts/build_financial_facts.py"
    )

    st.stop()


# -----------------------------------------------------------------------------
# Загрузка ассистента
# -----------------------------------------------------------------------------

with st.spinner(
    "Загрузка моделей и данных..."
):
    assistant = load_assistant()


# -----------------------------------------------------------------------------
# Форма вопроса
# -----------------------------------------------------------------------------

with st.form(
    "question_form"
):
    question = st.text_area(
        "Ваш вопрос",
        placeholder=(
            "Например: Как изменилась выручка "
            "Роснефти с 2024 по 2025 год?"
        ),
        height=120,
    )

    submitted = st.form_submit_button(
        "Получить ответ",
        type="primary",
    )


# -----------------------------------------------------------------------------
# Обработка вопроса
# -----------------------------------------------------------------------------

if submitted:
    if not question.strip():
        st.warning(
            "Введите вопрос."
        )

    else:
        with st.spinner(
            "Анализирую вопрос..."
        ):
            try:
                answer = assistant.ask_text(
                    question
                )

            except Exception:
                logger.exception(
                    "Ошибка при обработке вопроса"
                )

                st.error(
                    "Не удалось обработать вопрос. "
                    "Проверьте, запущен ли Ollama и доступны ли "
                    "необходимые модели и данные."
                )

            else:
                st.subheader(
                    "Ответ"
                )

                with st.container(
                    border=True
                ):
                    st.markdown(
                        answer
                    )


# -----------------------------------------------------------------------------
# Пояснение архитектуры
# -----------------------------------------------------------------------------

st.divider()

with st.expander(
    "Как система формирует ответ"
):
    st.markdown(
        """
Система использует разные механизмы в зависимости от вопроса:

**Текстовые вопросы**

`годовой отчет → retrieval → reranker → LLM → ответ с источниками`

**Точные финансовые значения**

`FinancialFact Store → точное значение → provenance`

**Расчеты**

`FinancialFact Store → Python → результат`

LLM не используется для детерминированной финансовой арифметики.
"""
    )


st.caption(
    "Инструмент предназначен для аналитической поддержки. "
    "Финальные инвестиционные и кредитные решения "
    "принимаются пользователем."
)
def build_system_prompt() -> str:
    """
    Формирует системную инструкцию для grounded generation.
    """
    return (
        "Ты — помощник кредитного аналитика.\n"
        "\n"
        "Отвечай только на основании предоставленного контекста.\n"
        "Не используй собственные знания и не добавляй факты, "
        "которых нет в контексте.\n"
        "Не показывай ход рассуждений. Верни только конечный ответ.\n"
        "\n"
        "Правила ответа:\n"
        "1. Используй только факты из блоков SOURCE.\n"
        "2. Включай только факты, которые непосредственно отвечают на вопрос.\n"
        "3. После каждого существенного утверждения или пункта обязательно "
        "указывай подтверждающий источник точно в формате [SOURCE N].\n"
        "4. Не объединяй несколько ссылок в конце всего ответа, если разные "
        "утверждения подтверждаются разными источниками.\n"
        "5. Не используй другие форматы ссылок на источники.\n"
        "6. Не ссылайся на SOURCE, если он не подтверждает утверждение.\n"
        "7. Если источник не относится к вопросу, не используй его.\n"
        "8. Не придумывай значения, события, причины или выводы.\n"
        "9. Если контекста недостаточно для ответа, напиши только: "
        "\"В предоставленных источниках недостаточно информации.\"\n"
        "10. Отвечай на русском языке.\n"
        "11. Ответ должен быть кратким и по существу."
    )


def build_user_prompt(
    question: str,
    context: str,
) -> str:
    """
    Формирует пользовательскую часть prompt из вопроса и контекста.
    """
    return (
        f"ВОПРОС:\n"
        f"{question.strip()}\n"
        "\n"
        f"КОНТЕКСТ:\n"
        f"{context.strip()}\n"
        "\n"
        "Дай только конечный ответ. Используй только информацию, "
        "непосредственно отвечающую на вопрос, и после каждого пункта "
        "укажи источник вида [SOURCE N]."
    )